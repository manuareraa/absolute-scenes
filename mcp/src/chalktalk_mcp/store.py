"""Where the tools get frames and events from.

Two sources, both returning contract frames and events:
- a match package on disk (``sim`` package format: manifest, events, gzip chunks), read one
  chunk at a time with a small cache;
- a match regenerated by ``chalktalk_sim`` from its config. The config comes from a package
  manifest when there is one (so the tools see exactly what the browser plays), otherwise
  from ``CHALKTALK_SIM_HALF_MINUTES`` and the demo beats.

Match ids are ``sim-<seed>``. The store keeps at most ``CHALKTALK_MAX_MATCHES`` (default 2)
generated matches in memory; a full 90-minute match is about 65 MB of arrays.
"""

from __future__ import annotations

import json
import os
import re
from collections import OrderedDict
from functools import lru_cache
from pathlib import Path
from typing import Any

from chalktalk_core.geometry import FRAME_MS
from chalktalk_sim import DEMO_BEATS, Match, MatchConfig, config_from_meta, simulate
from chalktalk_sim.package import read_chunk

SIM_ID = re.compile(r"^sim-(\d{1,9})$")
MAX_WINDOW_MS = 180_000


class UnknownMatch(KeyError):
    pass


class Source:
    match_id: str
    info: dict[str, Any]

    @property
    def duration_ms(self) -> int:
        return int(self.info["duration_ms"])

    def clamp(self, t: int) -> int:
        t = int(t)
        if t < 0 or t > self.duration_ms:
            raise ValueError(f"t={t} outside the match (0..{self.duration_ms} ms)")
        return round(t / FRAME_MS) * FRAME_MS

    def frame(self, t: int) -> dict[str, Any]:
        raise NotImplementedError

    def window(self, start_t: int, end_t: int, max_frames: int = 400) -> list[dict[str, Any]]:
        """Frames from start_t to end_t inclusive, thinned evenly to at most ``max_frames``."""
        a, b = self.clamp(start_t), self.clamp(end_t)
        if b < a:
            raise ValueError("end_t before start_t")
        if b - a > MAX_WINDOW_MS:
            raise ValueError(f"window longer than {MAX_WINDOW_MS // 1000} s")
        n = (b - a) // FRAME_MS + 1
        step = max(1, -(-n // max_frames))
        ts = list(range(a, b + 1, FRAME_MS * step))
        if ts[-1] != b:
            ts.append(b)
        return [self.frame(t) for t in ts]

    def events(self) -> list[dict[str, Any]]:
        raise NotImplementedError


class SimSource(Source):
    def __init__(self, match: Match):
        self.match = match
        self.info = match.info()
        self.match_id = self.info["match_id"]

    def frame(self, t: int) -> dict[str, Any]:
        return self.match.frame(min(self.clamp(t) // FRAME_MS, self.match.n_frames - 1))

    def events(self) -> list[dict[str, Any]]:
        return self.match.events


class PackageSource(Source):
    def __init__(self, root: Path):
        self.root = root
        self.info = json.loads((root / "manifest.json").read_text())
        self.match_id = self.info["match_id"]
        self._events: list[dict[str, Any]] | None = None
        self._chunk = lru_cache(maxsize=6)(lambda file: read_chunk(self.root, file))

    def frame(self, t: int) -> dict[str, Any]:
        t = self.clamp(t)
        for c in self.info["chunks"]:
            if c["start_t"] <= t <= c["end_t"]:
                return self._chunk(c["file"])[(t - c["start_t"]) // FRAME_MS]
        last = self.info["chunks"][-1]
        return self._chunk(last["file"])[-1]

    def events(self) -> list[dict[str, Any]]:
        if self._events is None:
            self._events = json.loads((self.root / self.info["events"]["file"]).read_text())
        return self._events


class Store:
    def __init__(
        self,
        packages: Path | str | None = None,
        half_minutes: float | None = None,
        max_matches: int | None = None,
        prefer_packages: bool = True,
    ):
        env = os.environ
        packages = packages or env.get("CHALKTALK_PACKAGES")
        self.packages = Path(packages) if packages else None
        self.half_minutes = float(half_minutes or env.get("CHALKTALK_SIM_HALF_MINUTES", 45))
        self.max_matches = int(max_matches or env.get("CHALKTALK_MAX_MATCHES", 2))
        self.prefer_packages = prefer_packages
        self._cache: OrderedDict[str, Source] = OrderedDict()

    def _package_dir(self, match_id: str) -> Path | None:
        if self.packages is None:
            return None
        d = self.packages / match_id
        return d if (d / "manifest.json").is_file() else None

    def list(self) -> list[dict[str, Any]]:
        out = []
        if self.packages and self.packages.is_dir():
            for d in sorted(self.packages.iterdir()):
                if (d / "manifest.json").is_file() and SIM_ID.match(d.name):
                    m = json.loads((d / "manifest.json").read_text())
                    out.append(_summary(m, "package"))
        for mid, src in self._cache.items():
            if not any(o["match_id"] == mid for o in out):
                out.append(_summary(src.info, "generated"))
        return out

    def get(self, match_id: str) -> Source:
        if match_id in self._cache:
            self._cache.move_to_end(match_id)
            return self._cache[match_id]
        m = SIM_ID.match(match_id or "")
        if not m:
            raise UnknownMatch(f"unknown match {match_id!r}; ids look like 'sim-7'")
        seed = int(m.group(1))
        pkg = self._package_dir(match_id)
        if pkg is not None and self.prefer_packages:
            src: Source = PackageSource(pkg)
        elif pkg is not None:
            meta = json.loads((pkg / "manifest.json").read_text())
            src = SimSource(simulate(config_from_meta(seed, meta)))
        else:
            cfg = MatchConfig(seed=seed, half_minutes=self.half_minutes, beats=DEMO_BEATS)
            src = SimSource(simulate(cfg))
        self._cache[match_id] = src
        while len(self._cache) > self.max_matches:
            self._cache.popitem(last=False)
        return src

    def put(self, match: Match) -> Source:
        """Register an in-memory match (tests, notebooks)."""
        src = SimSource(match)
        self._cache[src.match_id] = src
        return src


def _summary(info: dict[str, Any], source: str) -> dict[str, Any]:
    return {
        "match_id": info["match_id"],
        "source": source,
        "duration_ms": info["duration_ms"],
        "teams": {k: v["name"] for k, v in info["teams"].items()},
        "score": info.get("score"),
    }
